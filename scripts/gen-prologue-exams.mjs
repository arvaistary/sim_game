function writeBank(fileName, exportName, questions) {
  const body = `import type { PrologueExamQuestion } from '@/domain/prologue/prologue.types'

/** Банк вопросов экзамена. */
export const ${exportName}: PrologueExamQuestion[] = ${JSON.stringify(questions, null, 2)}
`
  fs.writeFileSync(`src/domain/balance/constants/prologue/${fileName}`, body)
}

// extend types
const typesPath = 'src/domain/prologue/prologue.types.ts'
let typesSource = fs.readFileSync(typesPath, 'utf8')
if (!typesSource.includes('PrologueExamQuestion')) {
  typesSource += `

/** Вопрос экзамена пролога. */
export interface PrologueExamQuestion {
  id: string
  prompt: string
  options: [string, string, string]
  correctIndex: 0 | 1 | 2
}
`
  fs.writeFileSync(typesPath, typesSource)
}

